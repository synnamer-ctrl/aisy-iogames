# Writes the composed pages (JSON) as the ES module the Paint game imports.
import json, sys
pages = json.load(open(sys.argv[1]))
out = ['''// Colouring pages (viewBox 0 0 400 300), generated by tools/paint-pages/build.sh
// from CC0 vector art: Openclipart cartoon animals plus Kenney scenery, suns,
// mushrooms, coins and shape buddies. Every element with class "rg" is a paint
// area: free-hand strokes started inside it are clipped to its shape, so colour
// never crosses the line. Later areas sit on top of earlier ones. Elements with
// class "deco" (eyes, whiskers, details) are drawn over the paint.

export const PAGES = [''']
for name, svg in pages:
    out.append(f'  {{ name: {json.dumps(name)}, svg: {json.dumps(svg)} }},')
out.append('];\n')
open(sys.argv[2], 'w').write('\n'.join(out))
print(len(pages), 'pages')
